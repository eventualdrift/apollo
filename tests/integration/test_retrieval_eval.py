"""The retrieval suite in CI (spec J.4, O.1/24): no model, fully deterministic.

Each case file's fixture is loaded into a database of its own, and its cases
run under every candidate in the selection sweep: both text-search
configurations retrieval supports (spec E.4) at each floor on the grid.

Two records are held against that one run:

- `evals/retrieval/baseline.json`: each configuration at the default floor
  must not get worse than recorded. No metric drops, no case that passes there
  starts failing, and a case that fails there fails in no new way.
- `evals/retrieval/selection.json`: the sweep itself, and the settings it
  selects. The defaults in `RetrievalSettings` must be what the tuning cases
  select, so the defaults cannot drift from the evidence for them.

Both are bound to the corpus digest. To regenerate them deliberately, after a
change to the cases or to retrieval, run this module with
`APOLLO_REGENERATE_RETRIEVAL_RECORDS=1` and commit the result with the reason.
"""

from __future__ import annotations

import dataclasses
import json
import os
import pathlib
from typing import Any

import pytest

from apollo.evals.retrieval import (
    SPLITS,
    CaseResult,
    Metrics,
    corpus_digest,
    load_case_files,
    metrics,
    run_file,
    select_settings,
    sweep_grid,
    unexpected_failures,
)
from apollo.memory.retrieval import DEFAULT_SETTINGS, RetrievalSettings
from apollo.storage.repositories.retrieval import TEXT_SEARCH_CONFIGS

pytestmark = pytest.mark.integration

ROOT = pathlib.Path(__file__).resolve().parents[2] / "evals" / "retrieval"
BASELINE = ROOT / "baseline.json"
SELECTION = ROOT / "selection.json"
HIGHER_IS_BETTER = ("passed", "recall@5", "precision@5", "correct_empty_rate")
REGENERATE = os.environ.get("APOLLO_REGENERATE_RETRIEVAL_RECORDS") == "1"
UNEXPLAINED = "unexplained: say why this case fails before committing"


@dataclasses.dataclass(frozen=True)
class Sweep:
    digest: str
    results: dict[RetrievalSettings, list[CaseResult]]

    def metrics(self, settings: RetrievalSettings, split: str) -> Metrics:
        return metrics([r for r in self.results[settings] if r.case.split == split])

    def report(self, settings: RetrievalSettings) -> dict[str, dict[str, float | int]]:
        return {split: self.metrics(settings, split).as_dict() for split in SPLITS}


@pytest.fixture(scope="module")
def sweep(module_database_factory) -> Sweep:
    case_files = load_case_files(ROOT / "cases")
    grid = sweep_grid()
    results: dict[RetrievalSettings, list[CaseResult]] = {s: [] for s in grid}
    for case_file in case_files:
        for settings, found in run_file(module_database_factory(), case_file, grid).items():
            results[settings] += found
    run = Sweep(corpus_digest(case_files), results)
    if REGENERATE:
        # The documented way to rewrite both records: from a real run, on purpose.
        _write(BASELINE, _baseline_document(run, json.loads(BASELINE.read_text())))
        _write(SELECTION, _selection_document(run))
    return run


def _at_default_floor(config: str) -> RetrievalSettings:
    return dataclasses.replace(DEFAULT_SETTINGS, text_search_config=config)


def _selection_document(sweep: Sweep) -> dict[str, Any]:
    chosen = select_settings({s: sweep.metrics(s, "tune") for s in sweep.results})
    return {
        "note": (
            "The sweep behind RetrievalSettings' lexical_floor and text_search_config "
            "(spec E.4). select_settings chooses on the tuning cases; the held-out cases "
            "judge the choice. Generated by tests/integration/test_retrieval_eval.py with "
            "APOLLO_REGENERATE_RETRIEVAL_RECORDS=1; CI fails if a rerun differs."
        ),
        "corpus_sha256": sweep.digest,
        "selected": {
            "text_search_config": chosen.text_search_config,
            "lexical_floor": chosen.lexical_floor,
            "holdout": sweep.report(chosen)["holdout"],
        },
        "candidates": [
            {
                "text_search_config": s.text_search_config,
                "lexical_floor": s.lexical_floor,
                **sweep.report(s),
            }
            for s in sweep.results
        ],
    }


def _baseline_document(sweep: Sweep, previous: dict[str, Any]) -> dict[str, Any]:
    configs: dict[str, Any] = {}
    for config in TEXT_SEARCH_CONFIGS:
        settings = _at_default_floor(config)
        reasons = previous.get("configs", {}).get(config, {}).get("known_failures", {})
        configs[config] = {
            "splits": sweep.report(settings),
            "known_failures": {
                r.case.id: {
                    "failures": sorted(r.failures),
                    "reason": reasons.get(r.case.id, {}).get("reason", UNEXPLAINED),
                }
                for r in sweep.results[settings] if not r.passed
            },
        }
    return {
        "note": previous["note"],
        "corpus_sha256": sweep.digest,
        "lexical_floor": DEFAULT_SETTINGS.lexical_floor,
        "default_text_search_config": DEFAULT_SETTINGS.text_search_config,
        "configs": configs,
    }


def _write(path: pathlib.Path, document: dict[str, Any]) -> None:
    path.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def test_the_records_describe_this_corpus(sweep: Sweep) -> None:
    for path in (BASELINE, SELECTION):
        assert json.loads(path.read_text())["corpus_sha256"] == sweep.digest, (
            f"the cases changed since {path.name} was recorded; regenerate it deliberately, "
            "with the reason in the commit"
        )


@pytest.mark.parametrize("config", TEXT_SEARCH_CONFIGS)
def test_the_retrieval_suite_does_not_regress(sweep: Sweep, config: str) -> None:
    baseline = json.loads(BASELINE.read_text())
    assert (baseline["lexical_floor"], baseline["default_text_search_config"]) == (
        DEFAULT_SETTINGS.lexical_floor, DEFAULT_SETTINGS.text_search_config,
    ), "the baseline was recorded at different settings; regenerate it deliberately"
    assert set(baseline["configs"]) == set(TEXT_SEARCH_CONFIGS), (
        "every supported text-search configuration needs a baseline"
    )
    recorded = baseline["configs"][config]
    settings = _at_default_floor(config)
    report = sweep.report(settings)
    print(config, json.dumps(report, indent=2))  # visible with -s, and in CI logs on failure
    for split in SPLITS:
        before, now = recorded["splits"][split], report[split]
        assert now["cases"] == before["cases"], f"{config}/{split}: the corpus changed"
        for metric in HIGHER_IS_BETTER:
            assert now[metric] >= before[metric], (config, split, metric, now[metric],
                                                   before[metric])
        assert now["mean_rank_of_expected"] <= before["mean_rank_of_expected"], (config, split)

    known = {case_id: entry["failures"] for case_id, entry in recorded["known_failures"].items()}
    unexpected = unexpected_failures(sweep.results[settings], known)
    assert not unexpected, (config, unexpected)
    for case_id, entry in recorded["known_failures"].items():
        assert not entry["reason"].startswith("unexplained"), (config, case_id)


def test_the_defaults_are_what_the_tuning_cases_select(sweep: Sweep) -> None:
    """Spec E.4: settled by evidence. The default cannot drift from the sweep."""
    chosen = select_settings({s: sweep.metrics(s, "tune") for s in sweep.results})
    assert (chosen.text_search_config, chosen.lexical_floor) == (
        DEFAULT_SETTINGS.text_search_config, DEFAULT_SETTINGS.lexical_floor,
    ), "RetrievalSettings' defaults are not what the sweep selects"
    assert chosen == DEFAULT_SETTINGS  # nothing else on the grid differs from the defaults


def test_the_recorded_sweep_is_what_a_rerun_produces(sweep: Sweep) -> None:
    """The selection record is evidence, so it must be reproducible, exactly."""
    assert json.loads(SELECTION.read_text()) == _selection_document(sweep)
